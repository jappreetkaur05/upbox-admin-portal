export function seedZonesForWarehouse(warehouseId: string): WarehouseZoneRecord[] {
  return DEFAULT_ZONE_SEEDS.map((z) => ({
    id: `wz-${warehouseId}-${z.code.toLowerCase()}`,
    warehouseId,
    code: z.code,
    name: z.name,
    purpose: z.purpose,
    status: 'active' as const,
    aisleCount: 0,
    capacityPercent: 0,
    workDescription: z.workDescription,
  }))
}
