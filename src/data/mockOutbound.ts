function line(
  id: string,
  sku: string,
  name: string,
  brandId: string,
  qty: number,
  loc: string | null,
  status: OutboundOrder['lines'][0]['status'] = 'PENDING'
): OutboundOrder['lines'][0] {
  return {
    id,
    sku,
    barcode: `BC-${sku}`,
    name,
    brandId,
    qty,
    qtyAllocated: status === 'PENDING' ? 0 : qty,
    qtyPicked: ['PICKED', 'PACKED', 'SHIPPED'].includes(status) ? qty : 0,
    qtyPacked: ['PACKED', 'SHIPPED'].includes(status) ? qty : 0,
    status,
    allocatedLocationCode: loc,
    allocatedBinId: loc ? `bin-${loc}` : null,
    unitWeightKg: 0.35,
    lengthCm: 28,
    widthCm: 18,
    heightCm: 10,
  }
}

